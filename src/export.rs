//! `pdo export`: write the live code as a Wrangler project. The class source is
//! copied byte for byte; a generated wrapper applies the object's migrations
//! on first construction and exposes the same HTTP surface as `pdo run`
//! (fetch passthrough plus POST /.pdo/rpc/<method>).

use std::path::Path;

use anyhow::{Context, Result};
use serde_json::json;

use crate::store::{DEFAULT_MAIN, Store};

pub fn export(file: &Path, out: &Path, worker_name: Option<&str>) -> Result<()> {
    let s = Store::open(file)?;
    let live = s.live_checkin()?;
    let files = s.files_at(&live)?;
    let class = s.meta_req("class")?;
    let name = s.meta_req("name")?;
    let main = s.meta("main")?.unwrap_or_else(|| DEFAULT_MAIN.to_string());
    std::fs::create_dir_all(out)?;
    for (p, c) in &files {
        let dest = out.join(p);
        if let Some(d) = dest.parent() {
            std::fs::create_dir_all(d)?;
        }
        std::fs::write(&dest, c).with_context(|| format!("writing {}", dest.display()))?;
    }
    let migrations: Vec<_> = s
        .migrations()?
        .into_iter()
        .map(|m| json!({ "seq": m.0, "name": m.1, "sql": m.2 }))
        .collect();
    std::fs::create_dir_all(out.join("pdo"))?;
    std::fs::write(
        out.join("pdo/migrations.js"),
        format!(
            "// Generated by pdo export from check-in {live}. Do not edit.\nexport default {};\n",
            serde_json::to_string_pretty(&migrations)?
        ),
    )?;
    let import = format!("../{main}");
    let worker = format!(
        r#"// Generated by pdo export from check-in {live}. Do not edit.
// The object's class is imported unchanged; this wrapper applies its
// migrations once per object and gives Cloudflare the same HTTP surface as
// `pdo run`: every request to fetch(), POST /.pdo/rpc/<method> for RPC.
import {{ DurableObject }} from "cloudflare:workers";
import * as mod from "{import}";
import MIGRATIONS from "./migrations.js";

const Base = mod[{class_json}];
const OBJECT_NAME = {name_json};

function migrate(sql) {{
  sql.exec("CREATE TABLE IF NOT EXISTS _pdo_migrations (seq INTEGER PRIMARY KEY, name TEXT NOT NULL)");
  const done = new Set(sql.exec("SELECT seq FROM _pdo_migrations").toArray().map((r) => r.seq));
  for (const m of MIGRATIONS) {{
    if (done.has(m.seq)) continue;
    sql.exec(m.sql);
    sql.exec("INSERT INTO _pdo_migrations (seq, name) VALUES (?, ?)", m.seq, m.name);
  }}
}}

export class {class} extends DurableObject {{
  constructor(ctx, env) {{
    super(ctx, env);
    ctx.storage.transactionSync(() => migrate(ctx.storage.sql));
    this.inner = new Base(ctx, env);
  }}
  fetch(request) {{
    return this.inner.fetch(request);
  }}
  alarm(info) {{
    return this.inner.alarm ? this.inner.alarm(info) : undefined;
  }}
  async pdoRpc(method, args) {{
    const NOT_RPC = ["constructor", "fetch", "alarm", "ctx", "env"];
    if (NOT_RPC.includes(method) || method.startsWith("_") || method in Object.prototype || typeof this.inner[method] !== "function") {{
      throw new Error(`${{method}} is not a public RPC method on this class`);
    }}
    const r = await this.inner[method](...args);
    return r === undefined ? null : r;
  }}
}}

export default {{
  async fetch(request, env) {{
    const stub = env.OBJ.get(env.OBJ.idFromName(OBJECT_NAME));
    const url = new URL(request.url);
    const m = url.pathname.match(/^\/\.pdo\/rpc\/([^/]+)$/);
    if (m && request.method === "POST") {{
      const text = await request.text();
      let args = text ? JSON.parse(text) : [];
      if (!Array.isArray(args)) args = [args];
      try {{
        return Response.json({{ result: await stub.pdoRpc(decodeURIComponent(m[1]), args) }});
      }} catch (e) {{
        return Response.json({{ error: String(e && e.message || e) }}, {{ status: 500 }});
      }}
    }}
    return stub.fetch(request);
  }},
}};
"#,
        class_json = serde_json::to_string(&class)?,
        name_json = serde_json::to_string(&name)?,
    );
    std::fs::write(out.join("pdo/worker.js"), worker)?;
    let wname = worker_name.map(|s| s.to_string()).unwrap_or_else(|| {
        format!("pdo-{}", name.to_lowercase().replace(|c: char| !c.is_ascii_alphanumeric(), "-"))
    });
    let wrangler = json!({
        "$schema": "node_modules/wrangler/config-schema.json",
        "name": wname,
        "main": "pdo/worker.js",
        "compatibility_date": "2026-11-01",
        "durable_objects": { "bindings": [ { "name": "OBJ", "class_name": class } ] },
        "migrations": [ { "tag": "v1", "new_sqlite_classes": [ class ] } ],
        "observability": { "enabled": true },
    });
    std::fs::write(out.join("wrangler.jsonc"), format!("// Generated by pdo export.\n{}\n", serde_json::to_string_pretty(&wrangler)?))?;
    Ok(())
}
