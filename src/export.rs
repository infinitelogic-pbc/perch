//! `perch export`: write the live code as a Wrangler project. Every file is
//! copied byte for byte, and a generated Worker of a few lines routes each
//! request to the one object's fetch().

use std::path::Path;

use anyhow::{Context, Result};
use serde_json::json;

use crate::store::{DEFAULT_MAIN, PUBLIC_DIR, Store};

/// Workers Static Assets: files per Worker version (Free, Paid).
const CF_ASSET_LIMITS: (usize, usize) = (20_000, 100_000);

pub fn export(file: &Path, out: &Path, worker_name: Option<&str>) -> Result<Vec<String>> {
    let s = Store::open(file)?;
    let live = s.live_checkin()?;
    let files = s.manifest_at(&live)?;
    let class = s.meta_req("class")?;
    let name = s.meta_req("name")?;
    std::fs::create_dir_all(out)?;
    for (p, hash) in &files {
        let c = s.blob(hash)?;
        let dest = out.join(p);
        if let Some(d) = dest.parent() {
            std::fs::create_dir_all(d)?;
        }
        std::fs::write(&dest, c).with_context(|| format!("writing {}", dest.display()))?;
    }
    std::fs::create_dir_all(out.join("perch"))?;
    let worker = format!(
        r#"// Generated by perch export from check-in {live}. Do not edit.
// The object's class is exported unchanged, schema steps and all. This Worker
// only routes: every request goes to the one object's fetch(), as `perch run`
// does. Static files under public/ are served by Cloudflare before it runs.
export {{ {class} }} from "../{main}";

const OBJECT_NAME = {name_json};

export default {{
  fetch(request, env) {{
    return env.OBJ.get(env.OBJ.idFromName(OBJECT_NAME)).fetch(request);
  }},
}};
"#,
        main = DEFAULT_MAIN,
        name_json = serde_json::to_string(&name)?,
    );
    std::fs::write(out.join("perch/worker.js"), worker)?;
    let wname = worker_name.map(|s| s.to_string()).unwrap_or_else(|| {
        format!("perch-{}", name.to_lowercase().replace(|c: char| !c.is_ascii_alphanumeric(), "-"))
    });
    let mut wrangler = json!({
        "$schema": "node_modules/wrangler/config-schema.json",
        "name": wname,
        "main": "perch/worker.js",
        "compatibility_date": "2026-11-01",
        "durable_objects": { "bindings": [ { "name": "OBJ", "class_name": class } ] },
        "migrations": [ { "tag": "v1", "new_sqlite_classes": [ class ] } ],
        // Text imports perch supports beyond wrangler's defaults (.html .txt .sql).
        "rules": [ { "type": "Text", "globs": ["**/*.css", "**/*.md", "**/*.svg"], "fallthrough": true } ],
        "observability": { "enabled": true },
    });
    // public/ becomes Workers Static Assets. Cloudflare's defaults (worker not
    // first, auto-trailing-slash, no not-found page) are the rules perch run uses.
    if files.keys().any(|p| p.starts_with(PUBLIC_DIR)) {
        wrangler["assets"] = json!({ "directory": "./public" });
    }
    std::fs::write(out.join("wrangler.jsonc"), format!("// Generated by perch export.\n{}\n", serde_json::to_string_pretty(&wrangler)?))?;
    let mut warnings = vec![];
    let statics = files.keys().filter(|p| p.starts_with(PUBLIC_DIR)).count();
    if statics > CF_ASSET_LIMITS.1 {
        warnings.push(format!(
            "public/ has {statics} files; Cloudflare Workers Static Assets allows {} per Worker version, so this deploy will be refused. Serve the files from R2 instead.",
            CF_ASSET_LIMITS.1
        ));
    } else if statics > CF_ASSET_LIMITS.0 {
        warnings.push(format!(
            "public/ has {statics} files; that needs the Workers Paid plan (the Free plan allows {} files per Worker version) and Wrangler 4.34 or later.",
            CF_ASSET_LIMITS.0
        ));
    }
    Ok(warnings)
}
