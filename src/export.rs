//! `perch export`: write the live code as a Wrangler project. The class source is
//! copied byte for byte; a generated wrapper applies the object's migrations
//! on first construction and exposes the same HTTP surface as `perch run`
//! (fetch passthrough plus POST /.perch/rpc/<method>).

use std::path::Path;

use anyhow::{Context, Result};
use serde_json::json;

use crate::store::{DEFAULT_MAIN, PUBLIC_DIR, Store};

/// Workers Static Assets: files per Worker version (Free, Paid).
const CF_ASSET_LIMITS: (usize, usize) = (20_000, 100_000);

pub fn export(file: &Path, out: &Path, worker_name: Option<&str>) -> Result<Vec<String>> {
    let s = Store::open(file)?;
    let live = s.live_checkin()?;
    let files = s.manifest_at(&live)?;
    let class = s.meta_req("class")?;
    let name = s.meta_req("name")?;
    let main = s.meta("main")?.unwrap_or_else(|| DEFAULT_MAIN.to_string());
    std::fs::create_dir_all(out)?;
    for (p, hash) in &files {
        let c = s.blob(hash)?;
        let dest = out.join(p);
        if let Some(d) = dest.parent() {
            std::fs::create_dir_all(d)?;
        }
        std::fs::write(&dest, c).with_context(|| format!("writing {}", dest.display()))?;
    }
    let migrations: Vec<_> = s
        .migrations()?
        .into_iter()
        .map(|m| json!({ "seq": m.0, "name": m.1, "sql": m.2 }))
        .collect();
    std::fs::create_dir_all(out.join("perch"))?;
    std::fs::write(
        out.join("perch/migrations.js"),
        format!(
            "// Generated by perch export from check-in {live}. Do not edit.\nexport default {};\n",
            serde_json::to_string_pretty(&migrations)?
        ),
    )?;
    let import = format!("../{main}");
    let worker = format!(
        r#"// Generated by perch export from check-in {live}. Do not edit.
// The object's class is imported unchanged; this wrapper applies its
// migrations once per object and gives Cloudflare the same HTTP surface as
// `perch run`: every request to fetch(), POST /.perch/rpc/<method> for RPC.
import {{ DurableObject }} from "cloudflare:workers";
import * as mod from "{import}";
import MIGRATIONS from "./migrations.js";

const Base = mod[{class_json}];
const OBJECT_NAME = {name_json};

function migrate(sql) {{
  sql.exec("CREATE TABLE IF NOT EXISTS _perch_migrations (seq INTEGER PRIMARY KEY, name TEXT NOT NULL)");
  const done = new Set(sql.exec("SELECT seq FROM _perch_migrations").toArray().map((r) => r.seq));
  for (const m of MIGRATIONS) {{
    if (done.has(m.seq)) continue;
    sql.exec(m.sql);
    sql.exec("INSERT INTO _perch_migrations (seq, name) VALUES (?, ?)", m.seq, m.name);
  }}
}}

export class {class} extends DurableObject {{
  constructor(ctx, env) {{
    super(ctx, env);
    ctx.storage.transactionSync(() => migrate(ctx.storage.sql));
    this.inner = new Base(ctx, env);
  }}
  fetch(request) {{
    if (typeof this.inner.fetch !== "function") return new Response("Not found", {{ status: 404 }});
    return this.inner.fetch(request);
  }}
  alarm(info) {{
    return this.inner.alarm ? this.inner.alarm(info) : undefined;
  }}
  async perchRpc(method, args) {{
    const NOT_RPC = ["constructor", "fetch", "alarm", "ctx", "env"];
    if (NOT_RPC.includes(method) || method.startsWith("_") || method in Object.prototype || typeof this.inner[method] !== "function") {{
      throw new Error(`${{method}} is not a public RPC method on this class`);
    }}
    const r = await this.inner[method](...args);
    return r === undefined ? null : r;
  }}
}}

export default {{
  async fetch(request, env) {{
    const stub = env.OBJ.get(env.OBJ.idFromName(OBJECT_NAME));
    const url = new URL(request.url);
    const m = url.pathname.match(/^\/\.perch\/rpc\/([^/]+)$/);
    if (m && request.method === "POST") {{
      const text = await request.text();
      let args = text ? JSON.parse(text) : [];
      if (!Array.isArray(args)) args = [args];
      try {{
        return Response.json({{ result: await stub.perchRpc(decodeURIComponent(m[1]), args) }});
      }} catch (e) {{
        return Response.json({{ error: String(e && e.message || e) }}, {{ status: 500 }});
      }}
    }}
    return stub.fetch(request);
  }},
}};
"#,
        class_json = serde_json::to_string(&class)?,
        name_json = serde_json::to_string(&name)?,
    );
    std::fs::write(out.join("perch/worker.js"), worker)?;
    let wname = worker_name.map(|s| s.to_string()).unwrap_or_else(|| {
        format!("perch-{}", name.to_lowercase().replace(|c: char| !c.is_ascii_alphanumeric(), "-"))
    });
    let mut wrangler = json!({
        "$schema": "node_modules/wrangler/config-schema.json",
        "name": wname,
        "main": "perch/worker.js",
        "compatibility_date": "2026-11-01",
        "durable_objects": { "bindings": [ { "name": "OBJ", "class_name": class } ] },
        "migrations": [ { "tag": "v1", "new_sqlite_classes": [ class ] } ],
        // Text imports perch supports beyond wrangler's defaults (.html .txt .sql).
        "rules": [ { "type": "Text", "globs": ["**/*.css", "**/*.md", "**/*.svg"], "fallthrough": true } ],
        "observability": { "enabled": true },
    });
    // public/ becomes Workers Static Assets. Cloudflare's defaults (worker not
    // first, auto-trailing-slash, no not-found page) are the rules perch run uses.
    if files.keys().any(|p| p.starts_with(PUBLIC_DIR)) {
        wrangler["assets"] = json!({ "directory": "./public" });
    }
    std::fs::write(out.join("wrangler.jsonc"), format!("// Generated by perch export.\n{}\n", serde_json::to_string_pretty(&wrangler)?))?;
    let mut warnings = vec![];
    let statics = files.keys().filter(|p| p.starts_with(PUBLIC_DIR)).count();
    if statics > CF_ASSET_LIMITS.1 {
        warnings.push(format!(
            "public/ has {statics} files; Cloudflare Workers Static Assets allows {} per Worker version, so this deploy will be refused. Serve the files from R2 instead.",
            CF_ASSET_LIMITS.1
        ));
    } else if statics > CF_ASSET_LIMITS.0 {
        warnings.push(format!(
            "public/ has {statics} files; that needs the Workers Paid plan (the Free plan allows {} files per Worker version) and Wrangler 4.34 or later.",
            CF_ASSET_LIMITS.0
        ));
    }
    Ok(warnings)
}
